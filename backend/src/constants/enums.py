from enum import Enum
class Role(str, Enum):
    ADMIN = "admin"
    ANALYST = "analyst"
    VIEWER = "viewer"
class RunStatus(str, Enum):
    QUEUED = "queued"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    INVALIDATED = "invalidated"
class ReviewStatus(str, Enum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"
    INVALIDATED = "invalidated"
class ReportStatus(str, Enum):
    ACTIVE = "active"
    INVALIDATED = "invalidated"
class SupplementStatus(str, Enum):
    APPLIED = "applied"
    NO_CHANGE = "no_change"
    QUARANTINED = "quarantined"
